//! Project clean-up: removes files Unity and IDEs regenerate (Library, Temp, Logs,
//! .sln/.csproj…) to free disk space.
//!
//! In a git repository the candidates are the untracked files git ignores, the same set
//! as `git clean -dX` (tracked and untracked-but-not-ignored files are never touched).
//! Without git, only well-known generated folders and files at the project root are
//! offered. Each item says what kind of file it is; `Other` items (ignored by git but not
//! regenerated, e.g. a Builds folder) are listed but not selected by default.

use std::collections::HashSet;
use std::fs;
use std::io;
use std::path::{Component, Path};
use std::process::{Command, Stdio};

use crate::details::dir_size;
use crate::error::{Result, UniHubError};
use crate::vcs;

#[derive(Debug, Clone, Copy, PartialEq, Eq, uniffi::Enum)]
pub enum CleanMethod {
    /// Untracked files ignored by the project's git repository.
    GitIgnored,
    /// Generated folders and files at the project root (no git repository).
    UnityGenerated,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, uniffi::Enum)]
pub enum CleanKind {
    /// Library, Temp, obj: Unity rebuilds them when the project opens.
    Cache,
    /// Logs and memory captures.
    Logs,
    /// Solution and project files, IDE caches: regenerated by Unity or the IDE.
    IdeFiles,
    /// Debug symbols and IL2CPP/Burst debug folders.
    DebugFiles,
    /// Finder metadata (.DS_Store).
    SystemFiles,
    /// Ignored by git, but nothing regenerates it (builds, local settings, assets kept
    /// out of the repository). Not selected by default.
    Other,
}

impl CleanKind {
    /// Selected by default in the UI and removed by `unihub clean` without `--all`.
    pub fn regenerated(self) -> bool {
        self != CleanKind::Other
    }
}

#[derive(Debug, Clone, PartialEq, Eq, uniffi::Record)]
pub struct CleanItem {
    /// Relative to the project folder, with `/` separators.
    pub path: String,
    pub is_dir: bool,
    pub bytes: u64,
    pub kind: CleanKind,
}

#[derive(Debug, Clone, PartialEq, Eq, uniffi::Record)]
pub struct CleanPlan {
    pub method: CleanMethod,
    /// Largest first.
    pub items: Vec<CleanItem>,
    pub total_bytes: u64,
    /// The project is open in a Unity editor: cleaning is refused until it closes.
    pub open_in_editor: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, uniffi::Record)]
pub struct CleanResult {
    pub removed: u32,
    pub freed_bytes: u64,
    /// `path: reason` for each item that could not be removed (fully).
    pub failed: Vec<String>,
}

/// What a clean-up of `project` would remove, with sizes.
pub fn plan(project: &Path) -> CleanPlan {
    let (method, candidates) = candidates(project);
    let mut items: Vec<CleanItem> = candidates
        .into_iter()
        .map(|(path, is_dir, kind)| {
            let full = project.join(&path);
            let bytes = if is_dir {
                dir_size(&full)
            } else {
                full.symlink_metadata().map_or(0, |m| m.len())
            };
            CleanItem { path, is_dir, bytes, kind }
        })
        .collect();
    items.sort_by(|a, b| b.bytes.cmp(&a.bytes).then_with(|| a.path.cmp(&b.path)));
    CleanPlan {
        method,
        total_bytes: items.iter().map(|i| i.bytes).sum(),
        items,
        open_in_editor: open_in_editor(project),
    }
}

/// Removes the given items (paths from `plan`). Only paths that are still clean-up
/// candidates are removed, so a stale or forged list cannot delete anything else.
pub fn clean(project: &Path, paths: &[String]) -> Result<CleanResult> {
    if open_in_editor(project) {
        return Err(UniHubError::ProjectInUse { path: project.to_string_lossy().into_owned() });
    }
    let allowed: HashSet<String> = candidates(project).1.into_iter().map(|(p, _, _)| p).collect();
    let mut result = CleanResult { removed: 0, freed_bytes: 0, failed: Vec::new() };
    for path in paths {
        if !allowed.contains(path) || !is_plain_relative(path) {
            result.failed.push(format!("{path}: not a clean-up candidate"));
            continue;
        }
        let mut freed = 0;
        match remove_tree(&project.join(path), &mut freed) {
            Ok(()) => result.removed += 1,
            Err(e) => result.failed.push(format!("{path}: {e}")),
        }
        result.freed_bytes += freed;
    }
    Ok(result)
}

/// `(relative path, is_dir, kind)` for every item a clean-up may remove.
fn candidates(project: &Path) -> (CleanMethod, Vec<(String, bool, CleanKind)>) {
    // Only run git inside a repository. If git is missing or fails, fall back to the
    // generated-files list below.
    if vcs::git_root(project).is_some()
        && let Some(ignored) = git_ignored(project)
    {
        let items = ignored
            .into_iter()
            .filter_map(|path| {
                let full = project.join(&path);
                let meta = full.symlink_metadata().ok()?;
                // Like `git clean` without -ff: leave nested repositories alone.
                if meta.is_dir() && full.join(".git").exists() {
                    return None;
                }
                let kind = classify(&path, meta.is_dir()).unwrap_or(CleanKind::Other);
                Some((path, meta.is_dir(), kind))
            })
            .collect();
        return (CleanMethod::GitIgnored, items);
    }
    let mut items = Vec::new();
    if let Ok(entries) = fs::read_dir(project) {
        for entry in entries.flatten() {
            let Ok(meta) = entry.path().symlink_metadata() else { continue };
            let name = entry.file_name().to_string_lossy().into_owned();
            if let Some(kind) = classify(&name, meta.is_dir()).filter(|k| *k != CleanKind::SystemFiles) {
                items.push((name, meta.is_dir(), kind));
            }
        }
    }
    (CleanMethod::UnityGenerated, items)
}

/// Untracked, ignored paths under `project` (directories collapsed), relative to it.
fn git_ignored(project: &Path) -> Option<Vec<String>> {
    let out = Command::new("/usr/bin/git")
        .arg("-C")
        .arg(project)
        .args(["ls-files", "--others", "--ignored", "--exclude-standard", "--directory", "-z"])
        .env("GIT_OPTIONAL_LOCKS", "0")
        .stdin(Stdio::null())
        .stderr(Stdio::null())
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    Some(
        out.stdout
            .split(|b| *b == 0)
            .filter(|s| !s.is_empty())
            .map(|s| String::from_utf8_lossy(s).trim_end_matches('/').to_string())
            .filter(|p| is_plain_relative(p))
            .collect(),
    )
}

/// Known generated files. Folders and IDE files count only at the project root;
/// `.DS_Store` counts anywhere.
fn classify(path: &str, is_dir: bool) -> Option<CleanKind> {
    let name = path.rsplit('/').next().unwrap_or(path).to_ascii_lowercase();
    if !is_dir && name == ".ds_store" {
        return Some(CleanKind::SystemFiles);
    }
    if path.contains('/') {
        return None;
    }
    if is_dir {
        return match name.as_str() {
            "library" | "temp" | "obj" | "exportedobj" | ".gradle" => Some(CleanKind::Cache),
            "logs" | "memorycaptures" => Some(CleanKind::Logs),
            ".vs" | ".consulo" => Some(CleanKind::IdeFiles),
            n if n.ends_with("_burstdebuginformation_donotship")
                || n.ends_with("_backupthisfolder_butdontshipitwithyourgame") =>
            {
                Some(CleanKind::DebugFiles)
            }
            _ => None,
        };
    }
    if name.starts_with("mono_crash.") {
        return Some(CleanKind::Logs); // crash dumps the editor leaves at the root
    }
    let ext = name.rsplit_once('.').map_or("", |(_, e)| e);
    match ext {
        "sln" | "slnx" | "csproj" | "unityproj" | "suo" | "user" | "userprefs" | "pidb" | "booproj"
        | "svd" | "opendb" => Some(CleanKind::IdeFiles),
        "db" if name.ends_with(".vc.db") => Some(CleanKind::IdeFiles),
        "pdb" | "mdb" => Some(CleanKind::DebugFiles),
        _ => None,
    }
}

/// No absolute paths, `..` or empty names: the item must stay inside the project.
fn is_plain_relative(path: &str) -> bool {
    !path.is_empty() && Path::new(path).components().all(|c| matches!(c, Component::Normal(_)))
}

/// Deletes a file, symlink (not its target) or folder tree, adding the bytes it frees.
fn remove_tree(path: &Path, freed: &mut u64) -> io::Result<()> {
    let meta = path.symlink_metadata()?;
    if !meta.is_dir() {
        fs::remove_file(path)?;
        *freed += meta.len();
        return Ok(());
    }
    // Unity marks some cache folders read-only; their entries cannot be removed otherwise.
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mode = meta.permissions().mode();
        if mode & 0o700 != 0o700 {
            fs::set_permissions(path, fs::Permissions::from_mode(mode | 0o700))?;
        }
    }
    for entry in fs::read_dir(path)? {
        remove_tree(&entry?.path(), freed)?;
    }
    fs::remove_dir(path)
}

/// True when a Unity editor has the project open: it holds a lock on
/// `Temp/UnityLockfile` (a leftover file from a crash is not locked), or a running
/// process was started with `-projectPath <project>`.
pub fn open_in_editor(project: &Path) -> bool {
    lockfile_held(&project.join("Temp/UnityLockfile")) || editor_process_running(project)
}

fn lockfile_held(lockfile: &Path) -> bool {
    let Ok(file) = fs::File::open(lockfile) else { return false };
    match file.try_lock() {
        Ok(()) => {
            let _ = file.unlock();
            false
        }
        Err(fs::TryLockError::WouldBlock) => true,
        Err(fs::TryLockError::Error(_)) => false,
    }
}

fn editor_process_running(project: &Path) -> bool {
    let Ok(out) = Command::new("/bin/ps").args(["-axww", "-o", "args="]).stderr(Stdio::null()).output() else {
        return false;
    };
    let wanted = project.to_string_lossy();
    let wanted = wanted.trim_end_matches('/');
    String::from_utf8_lossy(&out.stdout).lines().any(|line| {
        let lower = line.to_ascii_lowercase();
        let Some(at) = lower.find("-projectpath ") else { return false };
        let rest = line[at + "-projectpath ".len()..].trim_start();
        let rest = rest.trim_start_matches('"');
        // The path may contain spaces, so compare the prefix and check where it ends.
        rest.strip_prefix(wanted)
            .is_some_and(|tail| tail.is_empty() || tail.starts_with([' ', '"', '/']))
            && lower.contains("unity.app/contents/macos/unity")
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::process::Command;

    fn touch(root: &Path, rel: &str, bytes: usize) {
        let p = root.join(rel);
        fs::create_dir_all(p.parent().unwrap()).unwrap();
        fs::write(p, vec![b'x'; bytes]).unwrap();
    }

    fn unity_project(root: &Path) {
        touch(root, "Assets/Player.cs", 10);
        touch(root, "ProjectSettings/ProjectVersion.txt", 10);
        touch(root, "Library/ArtifactDB", 1000);
        touch(root, "Library/PackageCache/com.unity.ugui/a.cs", 500);
        touch(root, "Temp/x", 5);
        touch(root, "Logs/Editor.log", 50);
        touch(root, "Game.sln", 20);
        touch(root, "Assembly-CSharp.csproj", 30);
        touch(root, "Builds/Game.app", 200);
        touch(root, "Game_BurstDebugInformation_DoNotShip/a.txt", 7);
        touch(root, "mono_crash.mem.123.1.blob", 9);
    }

    fn paths(plan: &CleanPlan) -> Vec<&str> {
        let mut v: Vec<&str> = plan.items.iter().map(|i| i.path.as_str()).collect();
        v.sort();
        v
    }

    #[test]
    fn without_git_offers_only_generated_root_items() {
        let dir = tempfile::tempdir().unwrap();
        unity_project(dir.path());
        let plan = plan(dir.path());
        assert_eq!(plan.method, CleanMethod::UnityGenerated);
        assert_eq!(
            paths(&plan),
            [
                "Assembly-CSharp.csproj",
                "Game.sln",
                "Game_BurstDebugInformation_DoNotShip",
                "Library",
                "Logs",
                "Temp",
                "mono_crash.mem.123.1.blob"
            ]
        );
        assert_eq!(plan.items[0].path, "Library");
        assert_eq!(plan.items[0].bytes, 1500);
        assert_eq!(plan.items[0].kind, CleanKind::Cache);
        assert!(!plan.open_in_editor);
    }

    #[test]
    fn with_git_offers_ignored_files_only() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        unity_project(root);
        touch(root, ".gitignore", 0);
        fs::write(root.join(".gitignore"), "/Library/\n/Temp/\n/Logs/\n/Builds/\n*.sln\n*.csproj\nAssets/Secret/\n").unwrap();
        touch(root, "Assets/Secret/key.txt", 3);
        touch(root, "Assets/NewScript.cs", 4); // untracked but not ignored: kept
        let git = |args: &[&str]| {
            assert!(Command::new("/usr/bin/git").arg("-C").arg(root).args(args).output().unwrap().status.success());
        };
        git(&["init", "-q"]);

        let plan = plan(root);
        assert_eq!(plan.method, CleanMethod::GitIgnored);
        assert_eq!(
            paths(&plan),
            ["Assembly-CSharp.csproj", "Assets/Secret", "Builds", "Game.sln", "Library", "Logs", "Temp"]
        );
        let kind = |p: &str| plan.items.iter().find(|i| i.path == p).unwrap().kind;
        assert_eq!(kind("Builds"), CleanKind::Other);
        assert_eq!(kind("Assets/Secret"), CleanKind::Other);
        assert_eq!(kind("Game.sln"), CleanKind::IdeFiles);
    }

    #[test]
    fn cleans_only_candidates() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        unity_project(root);
        // Read-only folder inside the cache, as Unity's package cache can be.
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(root.join("Library/PackageCache/com.unity.ugui"), fs::Permissions::from_mode(0o555)).unwrap();
        }
        let asked: Vec<String> =
            ["Library", "Game.sln", "Assets", "../outside", "Builds"].iter().map(|s| s.to_string()).collect();
        let result = clean(root, &asked).unwrap();
        assert_eq!(result.removed, 2);
        assert_eq!(result.freed_bytes, 1520);
        assert_eq!(result.failed.len(), 3);
        assert!(!root.join("Library").exists());
        assert!(!root.join("Game.sln").exists());
        assert!(root.join("Assets/Player.cs").exists());
        assert!(root.join("Builds/Game.app").exists());
        assert!(root.join("Temp/x").exists());
    }

    #[test]
    fn leftover_lockfile_is_not_an_open_editor() {
        let dir = tempfile::tempdir().unwrap();
        touch(dir.path(), "Temp/UnityLockfile", 0);
        assert!(!open_in_editor(dir.path()));

        let held = fs::File::open(dir.path().join("Temp/UnityLockfile")).unwrap();
        held.lock().unwrap();
        assert!(lockfile_held(&dir.path().join("Temp/UnityLockfile")));
        assert!(clean(dir.path(), &["Temp".into()]).is_err());
    }

    #[test]
    fn rejects_paths_leaving_the_project() {
        assert!(is_plain_relative("Library"));
        assert!(is_plain_relative("Assets/Secret"));
        assert!(!is_plain_relative("../x"));
        assert!(!is_plain_relative("/etc"));
        assert!(!is_plain_relative(""));
        assert!(!is_plain_relative("a/../../b"));
    }
}
